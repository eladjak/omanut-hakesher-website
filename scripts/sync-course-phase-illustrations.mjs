import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const courseRoot = path.resolve(websiteRoot, "..", "omanut-hakesher-course");
const sourceRoot = path.join(courseRoot, "assets", "illustrations");
const manifestPath = path.join(sourceRoot, "phase-illustrations.json");
const publicRoot = path.join(websiteRoot, "public", "images", "course-phases");
const generatedPath = path.join(
  websiteRoot,
  "src",
  "generated",
  "course-phase-illustrations.ts",
);

const EXPECTED = [
  [1, "גישה", [1, 2, 3], "stage-1-approach.jpg"],
  [2, "תקשורת", [4, 5], "stage-2-communication.jpg"],
  [3, "מעבר ומשיכה", [6, 7, 8, 9], "stage-3-transition.jpg"],
  [4, "חיבור וכימיה", [10], "stage-4-chemistry.jpg"],
  [5, "אינטימיות", [11], "stage-5-intimacy.jpg"],
  [6, "מחויבות", [12], "stage-6-commitment.jpg"],
];

function validateManifest(manifest) {
  const issues = [];
  const add = (condition, code) => {
    if (!condition) issues.push(code);
  };

  add(manifest.contractVersion === 1, "contract-version");
  add(manifest.phases?.length === 6, "phase-count");
  const contract = (manifest.phases ?? []).map(({ phase, name, weeks, file }) => [
    phase,
    name,
    weeks,
    file,
  ]);
  add(JSON.stringify(contract) === JSON.stringify(EXPECTED), "phase-contract");

  const canonical = [manifest.hero, ...(manifest.phases ?? [])].filter(Boolean);
  add(new Set(canonical.map((item) => item.file)).size === 7, "unique-files");
  for (const item of canonical) {
    add(
      typeof item.alt === "string" && item.alt.trim().length >= 20,
      `human-alt:${item.file}`,
    );
    add(
      typeof item.file === "string" &&
        path.basename(item.file) === item.file &&
        /\.(?:jpe?g|png|webp)$/iu.test(item.file),
      `safe-file:${item.file}`,
    );
  }
  return issues;
}

const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");

async function buildArtifacts(manifest) {
  const canonical = [
    { kind: "hero", ...manifest.hero },
    ...manifest.phases.map((item) => ({ kind: "phase", ...item })),
  ];
  const assets = [];
  for (const item of canonical) {
    const sourcePath = path.join(sourceRoot, item.file);
    const bytes = await readFile(sourcePath);
    assets.push({
      ...item,
      sourcePath,
      destinationPath: path.join(publicRoot, item.file),
      sourceSha256: sha256(bytes),
      bytes,
    });
  }
  assert.equal(
    new Set(assets.map((item) => item.sourceSha256)).size,
    assets.length,
    "canonical phase illustrations must have unique bytes",
  );

  const hero = assets.find((item) => item.kind === "hero");
  const phases = assets
    .filter((item) => item.kind === "phase")
    .map(({ phase, name, weeks, file, alt, sourceSha256 }) => ({
      phase,
      name,
      weeks,
      src: `/images/course-phases/${file}`,
      alt,
      sourceSha256,
    }));
  const generated = `// Generated by scripts/sync-course-phase-illustrations.mjs. Do not edit manually.\n` +
    `// Source: ../omanut-hakesher-course/assets/illustrations/phase-illustrations.json\n\n` +
    `export const COURSE_HERO_ILLUSTRATION = ${JSON.stringify(
      {
        src: `/images/course-phases/${hero.file}`,
        alt: hero.alt,
        sourceSha256: hero.sourceSha256,
      },
      null,
      2,
    )} as const;\n\n` +
    `export const COURSE_PHASE_ILLUSTRATIONS = ${JSON.stringify(phases, null, 2)} as const;\n`;

  return { assets, generated };
}

async function writeArtifacts(artifacts) {
  await mkdir(publicRoot, { recursive: true });
  await mkdir(path.dirname(generatedPath), { recursive: true });
  for (const asset of artifacts.assets) {
    await copyFile(asset.sourcePath, asset.destinationPath);
  }
  await writeFile(generatedPath, artifacts.generated, "utf8");
}

async function checkArtifacts(artifacts) {
  const issues = [];
  for (const asset of artifacts.assets) {
    try {
      const destination = await readFile(asset.destinationPath);
      if (sha256(destination) !== asset.sourceSha256) {
        issues.push(`asset-hash-drift:${path.basename(asset.destinationPath)}`);
      }
    } catch {
      issues.push(`asset-missing:${path.basename(asset.destinationPath)}`);
    }
  }
  try {
    const generated = await readFile(generatedPath, "utf8");
    if (generated !== artifacts.generated) issues.push("generated-contract-drift");
  } catch {
    issues.push("generated-contract-missing");
  }
  return issues;
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
assert.deepEqual(validateManifest(manifest), []);

if (process.argv.includes("--self-test")) {
  const controls = [
    [
      { ...manifest, phases: manifest.phases.slice(0, 5) },
      "phase-count",
    ],
    [
      {
        ...manifest,
        phases: manifest.phases.map((item, index) =>
          index === 5 ? { ...item, phase: 5 } : item,
        ),
      },
      "phase-contract",
    ],
    [
      {
        ...manifest,
        phases: manifest.phases.map((item, index) =>
          index === 4 ? { ...item, file: "../escape.jpg" } : item,
        ),
      },
      "phase-contract",
    ],
    [
      {
        ...manifest,
        phases: manifest.phases.map((item, index) =>
          index === 0 ? { ...item, alt: "" } : item,
        ),
      },
      `human-alt:${manifest.phases[0].file}`,
    ],
  ];
  for (const [mutated, expectedIssue] of controls) {
    assert.ok(validateManifest(mutated).includes(expectedIssue));
  }
  console.log(`Course phase illustration sync self-test: PASS (${controls.length} negative controls)`);
  process.exit(0);
}

const artifacts = await buildArtifacts(manifest);
if (process.argv.includes("--check")) {
  const issues = await checkArtifacts(artifacts);
  assert.deepEqual(issues, []);
  console.log("Course phase illustration sync: CHECK PASS (1 hero + 6 phases, hashes and generated contract current)");
} else {
  await writeArtifacts(artifacts);
  const issues = await checkArtifacts(artifacts);
  assert.deepEqual(issues, []);
  console.log("Course phase illustration sync: WROTE 1 hero + 6 phases and generated contract");
}
